/// Язык интерфейса: 'ru' или 'ko'. Названия товаров всегда хранятся как есть (обычно по-корейски).
String get lang => store.settings['lang'] ?? 'ru';
bool get isKo => lang == 'ko';

String t(String k) => (isKo ? _ko[k] : _ru[k]) ?? _ru[k] ?? k;

String tf(String k, Map<String, Object> args) {
  var s = t(k);
  args.forEach((a, v) => s = s.replaceAll('{$a}', '$v'));
  return s;
}

String catName(Cat c) => isKo ? c.ko : c.n;

String daysWord(int n) => isKo ? '일' : plural(n, 'день', 'дня', 'дней');

String leftText(int? dl) {
  if (isKo) {
    if (dl == null) return '기한 미입력';
    if (dl < 0) return '${-dl}일 지남';
    if (dl == 0) return '오늘까지';
    if (dl == 1) return '내일까지 (1일 남음)';
    return '$dl일 남음';
  }
  if (dl == null) return 'срок не указан';
  if (dl < 0) return 'просрочено ${-dl} ${plural(-dl, 'день', 'дня', 'дней')} назад';
  if (dl == 0) return 'сегодня последний день';
  if (dl == 1) return 'остался 1 день (до завтра)';
  return 'осталось $dl ${plural(dl, 'день', 'дня', 'дней')}';
}

